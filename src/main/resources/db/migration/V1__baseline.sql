-- V1: 2026-10-15 운영 DB 구조(mysqldump --no-data) 기준 출발점.
--
-- 운영 DB 는 이 파일을 실행하지 않는다. Flyway 가 처음 켜질 때 baseline-on-migrate 로
-- "V1 까지 적용됨"이라고만 기록한다. 빈 DB(로컬·CI 통합 테스트)에서만 실제로 실행된다.
--
-- 운영 DB 에 남아 있는 대문자 PORTFOLIO 테이블은 코드에서 쓰지 않으므로(매퍼는 소문자 portfolio 사용) 넣지 않았다.
-- 문자 정렬(COLLATE)은 서버 기본값(MySQL 8: utf8mb4_0900_ai_ci)을 따른다.

CREATE TABLE USERS (
    USER_ID               BIGINT       NOT NULL AUTO_INCREMENT,
    EMAIL                 VARCHAR(100) NOT NULL,
    PASSWORD              VARCHAR(255) DEFAULT NULL,
    NAME                  VARCHAR(50)  DEFAULT NULL,
    NICKNAME              VARCHAR(50)  DEFAULT NULL,
    PHONE                 VARCHAR(20)  DEFAULT NULL,
    ADDRESS               VARCHAR(255) DEFAULT NULL,
    ADDRESS_DETAIL        VARCHAR(255) DEFAULT NULL,
    EMAIL_VERIFIED        CHAR(1)      DEFAULT 'N',
    EMAIL_VERIFY_TOKEN    VARCHAR(255) DEFAULT NULL,
    LOGIN_FAIL_CNT        INT          DEFAULT 0,
    ACCOUNT_LOCKED        CHAR(1)      DEFAULT 'N',
    CREATED_AT            DATETIME     DEFAULT CURRENT_TIMESTAMP,
    profile_image_url     VARCHAR(500) DEFAULT NULL,
    ROLE                  VARCHAR(20)  NOT NULL DEFAULT 'USER',
    PASSWORD_RESET_TOKEN  VARCHAR(255) DEFAULT NULL,
    PASSWORD_RESET_EXPIRY DATETIME     DEFAULT NULL,
    DELETED_AT            DATETIME     DEFAULT NULL,
    DELETE_REASON         VARCHAR(500) DEFAULT NULL,
    FORCE_PW_CHANGE       CHAR(1)      DEFAULT 'N',
    LOCKED_UNTIL          DATETIME     DEFAULT NULL,
    PRIMARY KEY (USER_ID),
    UNIQUE KEY EMAIL (EMAIL),
    UNIQUE KEY NICKNAME (NICKNAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE STOCK_ITEM (
    ITEM_ID    BIGINT       NOT NULL AUTO_INCREMENT,
    TICKER     VARCHAR(20)  NOT NULL,
    ITEM_NM    VARCHAR(100) NOT NULL,
    MARKET     VARCHAR(20)  DEFAULT NULL,
    CREATED_AT DATETIME     DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ITEM_ID),
    UNIQUE KEY TICKER (TICKER)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE STOCK_PRICE (
    PRICE_ID    BIGINT NOT NULL AUTO_INCREMENT,
    ITEM_ID     BIGINT NOT NULL,
    OPEN_PRICE  BIGINT DEFAULT NULL,
    CLOSE_PRICE BIGINT DEFAULT NULL,
    HIGH_PRICE  BIGINT DEFAULT NULL,
    LOW_PRICE   BIGINT DEFAULT NULL,
    VOLUME      BIGINT DEFAULT NULL,
    TRADE_DATE  DATE   DEFAULT NULL,
    PRIMARY KEY (PRICE_ID),
    KEY ITEM_ID (ITEM_ID),
    CONSTRAINT STOCK_PRICE_ibfk_1 FOREIGN KEY (ITEM_ID) REFERENCES STOCK_ITEM (ITEM_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE USER_WATCHLIST (
    WATCH_ID BIGINT   NOT NULL AUTO_INCREMENT,
    USER_ID  BIGINT   NOT NULL,
    ITEM_ID  BIGINT   NOT NULL,
    ADDED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (WATCH_ID),
    KEY USER_ID (USER_ID),
    KEY ITEM_ID (ITEM_ID),
    CONSTRAINT USER_WATCHLIST_ibfk_1 FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID),
    CONSTRAINT USER_WATCHLIST_ibfk_2 FOREIGN KEY (ITEM_ID) REFERENCES STOCK_ITEM (ITEM_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE portfolio (
    portfolio_id INT           NOT NULL AUTO_INCREMENT,
    user_id      BIGINT        NOT NULL,
    ticker       VARCHAR(20)   NOT NULL,
    stock_name   VARCHAR(100)  NOT NULL,
    quantity     DECIMAL(10,2) NOT NULL,
    buy_price    INT           NOT NULL,
    buy_date     VARCHAR(8)    NOT NULL,
    created_at   DATETIME      DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (portfolio_id),
    KEY fk_portfolio_user (user_id),
    CONSTRAINT fk_portfolio_user FOREIGN KEY (user_id) REFERENCES USERS (USER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PRICE_ALERT (
    ALERT_ID     BIGINT       NOT NULL AUTO_INCREMENT,
    USER_ID      BIGINT       NOT NULL,
    ITEM_ID      BIGINT       DEFAULT NULL,
    TICKER       VARCHAR(20)  NOT NULL,
    STOCK_NAME   VARCHAR(100) DEFAULT NULL,
    TARGET_PRICE BIGINT       NOT NULL,
    ALERT_TYPE   VARCHAR(10)  NOT NULL,
    IS_TRIGGERED CHAR(1)      DEFAULT 'N',
    CREATED_AT   DATETIME     DEFAULT CURRENT_TIMESTAMP,
    TRIGGERED_AT DATETIME     DEFAULT NULL,
    PRIMARY KEY (ALERT_ID),
    KEY USER_ID (USER_ID),
    CONSTRAINT PRICE_ALERT_ibfk_1 FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE REFRESH_TOKEN (
    TOKEN_ID   BIGINT       NOT NULL AUTO_INCREMENT,
    USER_ID    BIGINT       NOT NULL,
    TOKEN      VARCHAR(512) NOT NULL,
    EXPIRED_AT DATETIME     NOT NULL,
    CREATED_AT DATETIME     DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (TOKEN_ID),
    KEY USER_ID (USER_ID),
    CONSTRAINT REFRESH_TOKEN_ibfk_1 FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE USER_SOCIAL (
    social_id      INT          NOT NULL AUTO_INCREMENT,
    user_id        BIGINT       NOT NULL,
    provider       VARCHAR(20)  NOT NULL,
    provider_email VARCHAR(100) DEFAULT NULL,
    created_at     DATETIME     DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (social_id),
    UNIQUE KEY uq_user_provider (user_id, provider),
    UNIQUE KEY uq_social_provider_email (provider, provider_email),
    CONSTRAINT USER_SOCIAL_ibfk_1 FOREIGN KEY (user_id) REFERENCES USERS (USER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE CHAT_MESSAGE (
    MSG_ID     BIGINT       NOT NULL AUTO_INCREMENT,
    TICKER     VARCHAR(20)  NOT NULL,
    USER_EMAIL VARCHAR(100) DEFAULT NULL,
    NICKNAME   VARCHAR(50)  DEFAULT NULL,
    CONTENT    TEXT,
    CREATED_AT DATETIME     DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (MSG_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE CERTIFICATION_USE (
    IMP_UID    VARCHAR(64)  NOT NULL,
    USER_EMAIL VARCHAR(120) DEFAULT NULL,
    PURPOSE    VARCHAR(20)  NOT NULL,
    USED_AT    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (IMP_UID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
